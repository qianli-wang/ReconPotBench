def setup_logging(log_file: str) -> logging.Logger:
    logger = logging.getLogger("evaluate_three_dimensions")
    logger.setLevel(logging.INFO)
    logger.handlers.clear()

    fmt = logging.Formatter("[%(asctime)s] [%(levelname)s] %(message)s")
    console = logging.StreamHandler(sys.stdout)
    console.setFormatter(fmt)
    console.encoding = "utf-8"

    file_handler = logging.FileHandler(log_file, encoding="utf-8")
    file_handler.setFormatter(fmt)

    logger.addHandler(console)
    logger.addHandler(file_handler)
    return logger

def load_json_list(file_path: str, logger: logging.Logger) -> List[Dict[str, Any]]:
    path = Path(file_path)
    if not path.exists():
        raise FileNotFoundError(f"JSON file not found: {file_path}")

    with path.open("r", encoding="utf-8") as f:
        raw = json.load(f)

    if not isinstance(raw, list):
        raise ValueError(f"Root JSON must be a list: {file_path}")

    valid_items: List[Dict[str, Any]] = []
    for idx, item in enumerate(raw):
        if not isinstance(item, dict):
            logger.warning("item[%d] is not an object, skipping", idx)
            continue
        conv = item.get("conversations")
        if not isinstance(conv, list) or len(conv) != 6:
            logger.warning("item[%d] conversations structure is invalid, skipping", idx)
            continue
        valid_items.append(item)

    logger.info("Loaded %d / %d valid conversations from %s", len(valid_items), len(raw), file_path)
    return valid_items


def validate_alignment(
    result_data: List[Dict[str, Any]],
    reference_data: List[Dict[str, Any]],
) -> None:
    if len(result_data) != len(reference_data):
        raise ValueError(
            f"Result/reference conversation count mismatch: result={len(result_data)} reference={len(reference_data)}"
        )

    for idx, (result_item, reference_item) in enumerate(zip(result_data, reference_data)):
        result_conv = result_item["conversations"]
        reference_conv = reference_item["conversations"]
        if len(result_conv) != 6 or len(reference_conv) != 6:
            raise ValueError(f"Conversation[{idx}] does not contain exactly 6 messages")
        for msg_idx in range(6):
            result_msg = result_conv[msg_idx]
            reference_msg = reference_conv[msg_idx]
            if not isinstance(result_msg, dict) or not isinstance(reference_msg, dict):
                raise ValueError(f"Conversation[{idx}] message[{msg_idx}] is not an object")
            if result_msg.get("from") != reference_msg.get("from"):
                raise ValueError(
                    f"Conversation[{idx}] message[{msg_idx}] role mismatch: "
                    f"result={result_msg.get('from')} reference={reference_msg.get('from')}"
                )


def normalize_api_base(api_base: str) -> str:
    base = api_base.rstrip("/")
    if base.endswith("/chat/completions"):
        return base
    if base.endswith("/v1"):
        return base + "/chat/completions"
    return base + "/chat/completions"


def get_round_values(conversation: List[Dict[str, Any]]) -> Tuple[List[str], List[str]]:
    commands = []
    outputs = []
    for round_idx in range(3):
        human_msg = conversation[round_idx * 2]
        gpt_msg = conversation[round_idx * 2 + 1]
        commands.append(str(human_msg.get("value", "")))
        outputs.append(str(gpt_msg.get("value", "")))
    return commands, outputs


def build_history_contents(commands: List[str], outputs: List[str], round_number: int) -> str:
    if round_number == 1:
        parts = [commands[0]]
    elif round_number == 2:
        parts = [commands[0], outputs[0], commands[1]]
    else:
        parts = [commands[0], outputs[0], commands[1], outputs[1], commands[2]]
    return "\n".join(parts)


def add_prompt_block(lines: List[str], name: str, value: str) -> None:
    lines.append(f"{name}:")
    lines.append("<<<")
    lines.append(value)
    lines.append(">>>")
    lines.append("")


def build_user_prompt(
    result_conversation: List[Dict[str, Any]],
    reference_conversation: List[Dict[str, Any]],
) -> str:
    result_commands, result_outputs = get_round_values(result_conversation)
    _, reference_outputs = get_round_values(reference_conversation)

    lines: List[str] = [
        "Evaluate the following conversation variables exactly as defined in the system instructions.",
        "Return exactly one JSON object and nothing else.",
        "",
    ]

    add_prompt_block(lines, "auth_round1_cmd", result_commands[0])
    add_prompt_block(lines, "auth_round1_test_output", result_outputs[0])
    add_prompt_block(lines, "auth_round1_reference_output", reference_outputs[0])
    add_prompt_block(lines, "auth_round2_cmd", result_commands[1])
    add_prompt_block(lines, "auth_round2_test_output", result_outputs[1])
    add_prompt_block(lines, "auth_round2_reference_output", reference_outputs[1])
    add_prompt_block(lines, "auth_round3_cmd", result_commands[2])
    add_prompt_block(lines, "auth_round3_test_output", result_outputs[2])
    add_prompt_block(lines, "auth_round3_reference_output", reference_outputs[2])

    cons_round1_contents = build_history_contents(result_commands, result_outputs, 1)
    cons_round2_contents = build_history_contents(result_commands, result_outputs, 2)
    cons_round3_contents = build_history_contents(result_commands, result_outputs, 3)

    add_prompt_block(lines, "cons_round1_contents", cons_round1_contents)
    add_prompt_block(lines, "cons_round1_output", result_outputs[0])
    add_prompt_block(lines, "cons_round2_contents", cons_round2_contents)
    add_prompt_block(lines, "cons_round2_output", result_outputs[1])
    add_prompt_block(lines, "cons_round3_contents", cons_round3_contents)
    add_prompt_block(lines, "cons_round3_output", result_outputs[2])

    add_prompt_block(lines, "utility_round1_contents", cons_round1_contents)
    add_prompt_block(lines, "utility_round1_output", result_outputs[0])
    add_prompt_block(lines, "utility_round2_contents", cons_round2_contents)
    add_prompt_block(lines, "utility_round2_output", result_outputs[1])
    add_prompt_block(lines, "utility_round3_contents", cons_round3_contents)
    add_prompt_block(lines, "utility_round3_output", result_outputs[2])
    return "\n".join(lines).strip()


def extract_json_object(text: str) -> Dict[str, Any]:
    stripped = text.strip()
    if stripped.startswith("```"):
        stripped = re.sub(r"^```[a-zA-Z0-9_-]*\s*", "", stripped)
        stripped = re.sub(r"\s*```$", "", stripped)

    try:
        parsed = json.loads(stripped)
        if isinstance(parsed, dict):
            return parsed
    except Exception:
        pass

    for start_idx, ch in enumerate(stripped):
        if ch != "{":
            continue
        depth = 0
        in_string = False
        escaped = False
        for end_idx in range(start_idx, len(stripped)):
            current = stripped[end_idx]
            if in_string:
                if escaped:
                    escaped = False
                elif current == "\\":
                    escaped = True
                elif current == '"':
                    in_string = False
            else:
                if current == '"':
                    in_string = True
                elif current == "{":
                    depth += 1
                elif current == "}":
                    depth -= 1
                    if depth == 0:
                        candidate = stripped[start_idx : end_idx + 1]
                        parsed = json.loads(candidate)
                        if isinstance(parsed, dict):
                            return parsed
                        break

    raise ValueError("No valid JSON object found in model output")


def normalize_binary_score(value: Any, field_name: str) -> int:
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, int) and value in {0, 1}:
        return value
    if isinstance(value, str):
        cleaned = value.strip()
        if cleaned in {"0", "1"}:
            return int(cleaned)
    raise ValueError(f"{field_name} must be 0 or 1, got: {value!r}")


def normalize_utility_score(value: Any) -> int:
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, int) and 0 <= value <= 5:
        return value
    if isinstance(value, str):
        cleaned = value.strip()
        if cleaned in {"0", "1", "2", "3", "4", "5"}:
            return int(cleaned)
    raise ValueError(f"hacker_utility_score must be an integer from 0 to 5, got: {value!r}")


def normalize_consistency_score(value: Any) -> Any:
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, int) and value in {0, 1}:
        return value
    if isinstance(value, str):
        cleaned = value.strip().upper()
        if cleaned in {"0", "1"}:
            return int(cleaned)
        if cleaned in {"NA", "N/A"}:
            return "NA"
    raise ValueError(f"consistency_score must be 0, 1, or 'NA', got: {value!r}")


def normalize_scores(raw_scores: Dict[str, Any]) -> Dict[str, Any]:
    missing = EXPECTED_SCORE_KEYS - set(raw_scores.keys())
    if missing:
        raise ValueError(f"Missing score keys: {sorted(missing)}")

    return {
        "authenticity_score_round1": normalize_binary_score(
            raw_scores["authenticity_score_round1"], "authenticity_score_round1"
        ),
        "authenticity_score_round2": normalize_binary_score(
            raw_scores["authenticity_score_round2"], "authenticity_score_round2"
        ),
        "authenticity_score_round3": normalize_binary_score(
            raw_scores["authenticity_score_round3"], "authenticity_score_round3"
        ),
        "consistency_score": normalize_consistency_score(raw_scores["consistency_score"]),
        "hacker_utility_score": normalize_utility_score(raw_scores["hacker_utility_score"]),
    }


def call_gpt_5_4_mini(
    user_prompt: str,
    system_prompt: str,
    api_base: str,
    api_key: str,
    model: str,
    timeout: int,
    logger: logging.Logger,
) -> Dict[str, Any]:
    url = normalize_api_base(api_base)
    headers = {"Authorization": api_key, "Content-Type": "application/json"}
    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ],
    }

    backoff = 1.0
    last_error: Exception | None = None

    for attempt in range(1, MAX_RETRIES + 1):
        try:
            resp = requests.post(
                url,
                headers=headers,
                data=json.dumps(payload, ensure_ascii=False),
                timeout=timeout,
            )
            if resp.status_code >= 400:
                msg = f"HTTP {resp.status_code}: {resp.text[:1000]}"
                if resp.status_code in {401, 429, 500, 502, 503, 504} and attempt < MAX_RETRIES:
                    logger.warning("API error (attempt %d/%d): %s", attempt, MAX_RETRIES, msg)
                    time.sleep(backoff)
                    backoff *= 2
                    continue
                raise RuntimeError(msg)

            data = resp.json()
            choices = data.get("choices", [])
            if not choices:
                raise RuntimeError("API response missing choices")
            content = choices[0].get("message", {}).get("content", "")
            if not isinstance(content, str):
                raise RuntimeError("API response content is not a string")
            return normalize_scores(extract_json_object(content))
        except requests.Timeout as e:
            last_error = e
            if attempt >= MAX_RETRIES:
                break
            logger.warning("API timeout (attempt %d/%d), retrying...", attempt, MAX_RETRIES)
            time.sleep(backoff)
            backoff *= 2
        except requests.RequestException as e:
            last_error = e
            if attempt >= MAX_RETRIES:
                break
            logger.warning("API network error (attempt %d/%d): %s", attempt, MAX_RETRIES, str(e))
            time.sleep(backoff)
            backoff *= 2
        except Exception as e:
            last_error = e
            if attempt >= MAX_RETRIES:
                break
            logger.warning("Evaluation parse/call error (attempt %d/%d): %s", attempt, MAX_RETRIES, str(e))
            time.sleep(backoff)
            backoff *= 2

    raise RuntimeError(f"Evaluation API call failed after all retries: {last_error}")


def derive_output_paths(
    input_path: str,
    auth_output: str,
    consistency_output: str,
    utility_output: str,
) -> Tuple[str, str, str]:
    input_file = Path(input_path)
    parent = input_file.resolve().parent
    stem = input_file.stem

    resolved_auth = auth_output or str(parent / f"{stem}_authenticity_scores.json")
    resolved_consistency = consistency_output or str(parent / f"{stem}_consistency_scores.json")
    resolved_utility = utility_output or str(parent / f"{stem}_hacker_utility_scores.json")
    return resolved_auth, resolved_consistency, resolved_utility


def write_json(payload: Any, path: str) -> None:
    out_path = Path(path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)


def build_authenticity_record(
    conversation_index: int,
    conversation_item: Dict[str, Any],
    scores: Dict[str, Any],
) -> Dict[str, Any]:
    return {
        "conversation_index": conversation_index,
        "conversations": copy.deepcopy(conversation_item["conversations"]),
        "authenticity_score_round1": scores["authenticity_score_round1"],
        "authenticity_score_round2": scores["authenticity_score_round2"],
        "authenticity_score_round3": scores["authenticity_score_round3"],
    }


def build_consistency_record(
    conversation_index: int,
    conversation_item: Dict[str, Any],
    scores: Dict[str, Any],
) -> Dict[str, Any]:
    return {
        "conversation_index": conversation_index,
        "conversations": copy.deepcopy(conversation_item["conversations"]),
        "consistency_score": scores["consistency_score"],
    }


def build_utility_record(
    conversation_index: int,
    conversation_item: Dict[str, Any],
    scores: Dict[str, Any],
) -> Dict[str, Any]:
    return {
        "conversation_index": conversation_index,
        "conversations": copy.deepcopy(conversation_item["conversations"]),
        "hacker_utility_score": scores["hacker_utility_score"],
    }


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Evaluate result JSON across three dimensions with gpt-5.4-mini.")
    parser.add_argument("--input", required=True, help="Result JSON file to evaluate.")
    parser.add_argument("--reference-input", default=DEFAULT_REFERENCE_INPUT, help="Reference JSON file path.")
    parser.add_argument("--auth-output", default="", help="Authenticity score output JSON path.")
    parser.add_argument("--consistency-output", default="", help="Consistency score output JSON path.")
    parser.add_argument("--utility-output", default="", help="Hacker utility score output JSON path.")
    parser.add_argument("--log-file", default=DEFAULT_LOG_FILE, help="Log file path.")
    parser.add_argument("--api-base", default=DEFAULT_API_BASE, help="API base URL.")
    parser.add_argument("--api-key", default=DEFAULT_API_KEY, help="API key.")
    parser.add_argument("--model", default=DEFAULT_MODEL, help="Model name.")
    parser.add_argument("--timeout", type=int, default=TIMEOUT, help="Request timeout in seconds.")
    parser.add_argument("--sleep-seconds", type=float, default=0.2, help="Sleep between conversations.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    logger = setup_logging(args.log_file)
    start_ts = time.time()

    auth_output, consistency_output, utility_output = derive_output_paths(
        input_path=args.input,
        auth_output=args.auth_output,
        consistency_output=args.consistency_output,
        utility_output=args.utility_output,
    )

    logger.info("=== Multi-dimensional evaluation ===")
    logger.info("Input result file : %s", args.input)
    logger.info("Reference file    : %s", args.reference_input)
    logger.info("System prompt     : embedded in code")
    logger.info("Model             : %s", args.model)
    logger.info("API base          : %s", args.api_base)
    logger.info("Auth output       : %s", auth_output)
    logger.info("Consistency output: %s", consistency_output)
    logger.info("Utility output    : %s", utility_output)

    try:
        result_data = load_json_list(args.input, logger)
        reference_data = load_json_list(args.reference_input, logger)
        validate_alignment(result_data, reference_data)
    except Exception:
        logger.error("Failed to initialize evaluation inputs: %s", traceback.format_exc())
        return

    authenticity_results: List[Dict[str, Any]] = []
    consistency_results: List[Dict[str, Any]] = []
    utility_results: List[Dict[str, Any]] = []

    write_json(authenticity_results, auth_output)
    write_json(consistency_results, consistency_output)
    write_json(utility_results, utility_output)

    total = len(result_data)
    for idx in range(total):
        logger.info("Evaluating conversation [%d/%d] ...", idx + 1, total)
        result_item = result_data[idx]
        reference_item = reference_data[idx]

        try:
            user_prompt = build_user_prompt(
                result_conversation=result_item["conversations"],
                reference_conversation=reference_item["conversations"],
            )
            scores = call_gpt_5_4_mini(
                user_prompt=user_prompt,
                system_prompt=SYSTEM_PROMPT,
                api_base=args.api_base,
                api_key=args.api_key,
                model=args.model,
                timeout=args.timeout,
                logger=logger,
            )
            authenticity_results.append(build_authenticity_record(idx + 1, result_item, scores))
            consistency_results.append(build_consistency_record(idx + 1, result_item, scores))
            utility_results.append(build_utility_record(idx + 1, result_item, scores))

            write_json(authenticity_results, auth_output)
            write_json(consistency_results, consistency_output)
            write_json(utility_results, utility_output)
            logger.info(
                "Conversation [%d/%d] done: auth=(%s,%s,%s) consistency=%s utility=%s",
                idx + 1,
                total,
                scores["authenticity_score_round1"],
                scores["authenticity_score_round2"],
                scores["authenticity_score_round3"],
                scores["consistency_score"],
                scores["hacker_utility_score"],
            )
        except Exception:
            logger.error("Conversation [%d] failed: %s", idx + 1, traceback.format_exc())

        if idx < total - 1 and args.sleep_seconds > 0:
            time.sleep(args.sleep_seconds)

    elapsed = time.time() - start_ts
    logger.info("=== Finished ===")
    logger.info("Processed conversations: %d/%d", len(authenticity_results), total)
    logger.info("Elapsed: %.1fs", elapsed)


if __name__ == "__main__":
    main()
